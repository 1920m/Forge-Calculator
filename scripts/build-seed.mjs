// Small RFC 4180 reader: quoted trait descriptions contain commas and quotes.
export function parseCsv(text) {
  const rows = []; let row = []; let cell = ""; let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (char === '"') {
      if (quoted && text[i + 1] === '"') { cell += '"'; i++; }
      else quoted = !quoted;
    } else if (!quoted && (char === ',' || char === '\n')) {
      row.push(cell.replace(/\r$/, "")); cell = "";
      if (char === '\n') { rows.push(row); row = []; }
    } else cell += char;
  }
  if (quoted) throw new Error("Unterminated CSV field.");
  if (cell || row.length) { row.push(cell.replace(/\r$/, "")); rows.push(row); }
  const [header, ...records] = rows;
  return records.filter(r => r.some(Boolean)).map(r => {
    if (r.length !== header.length) throw new Error("Malformed CSV row.");
    return Object.fromEntries(header.map((name, i) => [name, r[i]]));
  });
}
